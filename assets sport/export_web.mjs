// Export gym_trainer_lod.obj into a compact binary-friendly JSON for a WebGL viewer.
import fs from 'node:fs';
const ROOT='/storage/emulated/0/Documents/fitpulse';
const MATID={steel:0,rubber:1,accent:2,leather:3};
const txt=fs.readFileSync(ROOT+'/assets/models/gym_trainer_lod.obj','utf8');
const vs=[],uvs=[],tri=[],mat=[];let cur=0;
for(const line of txt.split('\n')){
  if(!line)continue;
  const t=line.split(/\s+/);
  if(t[0]==='v')vs.push(+t[1],+t[2],+t[3]);
  else if(t[0]==='vt')uvs.push(+t[1],1-(+t[2]));
  else if(t[0]==='g')cur=MATID[t[1]]??0;
  else if(t[0]==='f'){
    const idx=t.slice(1).map(s=>{const p=s.split('/');return {v:+p[0]-1,vt:p[1]?+p[1]-1:0};});
    // triangulate fan
    for(let i=1;i<idx.length-1;i++){
      for(const q of [idx[0],idx[i],idx[i+1]]){
        tri.push(q.v,q.vt,cur);
      }
    }
  }
}
// bounding box
let mn=[1e9,1e9,1e9],mx=[-1e9,-1e9,-1e9];
for(let i=0;i<vs.length;i+=3)for(let k=0;k<3;k++){mn[k]=Math.min(mn[k],vs[i+k]);mx[k]=Math.max(mx[k],vs[i+k]);}
const verts=tri.length/3;
const out={
  vcount:verts,
  tri:verts,
  pos:Array.from(new Float32Array(vs)),
  uv:Array.from(new Float32Array(uvs)),
  idx:Array.from(new Uint32Array(tri.length)),
  bbox:{min:mn,max:mx}
};
// groups for draw-call splitting: contiguous material runs
const runs=[];let s=0;
for(let i=1;i<tri.length/3;i++){
  if(tri[i*3+2]!==tri[(i-1)*3+2]){runs.push({mat:tri[(i-1)*3+2],start:s*3,count:(i-s)*3});s=i;}
}
runs.push({mat:tri[(tri.length/3-1)*3+2],start:s*3,count:(tri.length/3-s)*3});
out.runs=runs;
const js='// auto-generated by tools/export_web.mjs\nwindow.GYM_MESH='+JSON.stringify(out)+';\n';
fs.writeFileSync(ROOT+'/web/mesh.js',js);
console.log('verts',vs.length/3,'uvs',uvs.length/2,'tri-corners',verts,'runs',runs.length,'jsonKB',(js.length/1024).toFixed(1));
console.log('bbox',JSON.stringify(out.bbox));
